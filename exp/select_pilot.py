"""Pilot subset of the Redux datasets, chosen from dataset properties only (never from accuracy).

Criteria, fixed before looking at any new result:
  1. Cost cap: drop the 10% most expensive datasets (MultiROCKET extraction + TabPFN 3.5 full-training run, from the logs).
  2. Strata: training-set size (tertiles of the eligible datasets) x number of classes (2 | 3-6 | 7+).
  3. Proportional allocation of N_PILOT datasets over the strata, random draw inside each one with a fixed seed.

Output: exp/pilot_datasets.yaml (list in the same format as the config.yaml files).
"""

import glob
import os

import numpy as np
import pandas as pd

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FEAT_DIR = os.path.join(BASE_DIR, "features", "feat", "multirocket", "redux")
SEED = 0
N_PILOT = 36
COST_CAP_QUANTILE = 0.90
EXCLUDED = {"Crop"}  # already out of the study (execution time)


def strip(s):
    return s.astype(str).str.replace(r"_(eq|nmv)$", "", regex=True)


def properties():
    rows = []
    for name in sorted(os.listdir(FEAT_DIR)):
        if name in EXCLUDED:
            continue
        d = os.path.join(FEAT_DIR, name)
        y = np.load(os.path.join(d, f"{name}_y.npy"), allow_pickle=True)
        n_train = int(np.load(os.path.join(d, f"{name}_ntrain.npy"))[0])
        counts = np.unique(y[:n_train], return_counts=True)[1]
        rows.append({"dataset": name, "n_train": n_train, "n_test": len(y) - n_train, "n_classes": len(counts),
                     "min_class": int(counts.min())})
    p = pd.DataFrame(rows).set_index("dataset")
    p["valid_k10"] = (p.min_class >= 10) & (10 * p.n_classes <= p.n_train)   # the four strategies run with K = 10
    return p


def cost_seconds():
    """Per-dataset cost of one resample: MultiROCKET extraction + mean TabPFN 3.5 full-training run (seconds)."""
    t = pd.concat([pd.read_csv(f) for f in glob.glob(os.path.join(BASE_DIR, "features/logs/multirocket/time/*.csv"))])
    t["dataset"] = strip(t.dataset)
    ext = t.drop_duplicates("dataset", keep="last").set_index("dataset").time_seconds
    r = pd.concat([pd.read_csv(f) for f in glob.glob(os.path.join(BASE_DIR, "outputs/full/3.5/multirocket/time/*.csv"))])
    r["dataset"] = strip(r.dataset)
    run = r.groupby("dataset").total_execution_time.mean()
    return (ext + run).rename("cost")


def allocate(sizes, total):
    """Proportional allocation (largest remainder), at least one dataset per non-empty stratum."""
    raw = sizes / sizes.sum() * total
    alloc = np.floor(raw).astype(int)
    for k in raw.index[np.argsort(-(raw - alloc).values)][: total - alloc.sum()]:
        alloc[k] += 1
    for k in alloc.index[(alloc == 0) & (sizes > 0)]:
        alloc[k] = 1
        alloc[alloc.idxmax()] -= 1
    return alloc


def main():
    p = properties().join(cost_seconds())
    assert p.cost.notna().all(), p[p.cost.isna()].index.tolist()
    cap = p.cost.quantile(COST_CAP_QUANTILE)
    elig = p[p.cost <= cap].copy()
    elig["size"] = pd.qcut(elig.n_train, 3, labels=["small", "medium", "large"])
    elig["classes"] = pd.cut(elig.n_classes, [0, 2, 6, np.inf], labels=["2", "3-6", "7+"])
    elig["stratum"] = elig["size"].astype(str) + "/" + elig["classes"].astype(str)
    sizes = elig.groupby("stratum").size()
    alloc = allocate(sizes, N_PILOT)
    rng = np.random.default_rng(SEED)
    chosen = []
    for s in sizes.index:
        names = sorted(elig.index[elig.stratum == s])
        chosen += list(rng.choice(names, size=alloc[s], replace=False))
    chosen = sorted(chosen)
    sel = elig.loc[chosen]

    print(f"datasets: {len(p)} | cost cap (p{int(100 * COST_CAP_QUANTILE)}): {cap:.0f} s -> {len(p) - len(elig)} excluded, "
          f"{p.cost[p.cost > cap].sum() / p.cost.sum():.0%} of the total cost")
    print("\nstrata (eligible -> pilot):")
    print(pd.DataFrame({"eligible": sizes, "pilot": alloc}).to_string())

    def desc(d):
        return {"n": len(d), "n_train med": d.n_train.median(), "n_train max": d.n_train.max(), "classes med": d.n_classes.median(),
                "classes max": d.n_classes.max(), "% K=10 invalid": round(100 * (~d.valid_k10).mean()), "cost share": f"{d.cost.sum() / p.cost.sum():.0%}"}
    print("\nall 141 :", desc(p))
    print("eligible:", desc(elig))
    print("pilot   :", desc(sel))

    out = os.path.join(BASE_DIR, "exp", "pilot_datasets.yaml")
    with open(out, "w") as f:
        f.write(f"# Pilot subset of Redux ({len(chosen)} datasets), generated by exp/select_pilot.py\n")
        f.write(f"# seed={SEED}; cost cap = p{int(100 * COST_CAP_QUANTILE)}; strata = train size (tertiles) x classes (2 | 3-6 | 7+)\n")
        f.write("datasets:\n")
        for n in chosen:
            f.write(f"    - {n}\n")
    print("\nwritten:", out)
    print(sel[["n_train", "n_classes", "min_class", "valid_k10", "stratum"]].to_string())


if __name__ == "__main__":
    main()
